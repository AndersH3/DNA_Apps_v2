@pytest.mark.parametrize("script", ["merge.py", "merge_ydata.py", "extract.py"])
def test_empty_input_outputs(script, tmp_path):
    source = tmp_path / "empty.txt"
    source.touch()
    if script == "merge_ydata.py":
        extra = ["--output-prefix", tmp_path / "empty-result"]
    else:
        extra = ["--output", tmp_path / "empty-result"]
    result = cli(script, source, *extra, cwd=tmp_path)
    assert result.returncode == 0, result.stderr
    if script == "merge.py":
        assert all(
            line.startswith("#") for line in (tmp_path / "empty-result").read_text().splitlines()
        )
    elif script == "extract.py":
        assert (tmp_path / "empty-result").read_text() == ""
    else:
        for suffix in ("out.txt", "positive.out.txt", "negative.out.txt"):
            assert (tmp_path / f"empty-result.{suffix}").read_text() == ""
        assert "snps: 0" in (tmp_path / "empty-result.report.out.txt").read_text()


def test_ydata_cli_existing_report_leaves_all_outputs_untouched(tmp_path):
    source = tmp_path / "input.txt"
    source.write_text("M1+")
