def test_merge_cli_roundtrip_and_file_location_error(tmp_path):
    a, b = tmp_path / "input one.txt", tmp_path / "two.txt"
    a.write_text("\ufeff# comment\nrs1 1 10 AA\nrs2 2 20 --\nrs3 X 30 AG\n", encoding="utf-8")
    b.write_text("rs1b 1 10 AA\nrs2b 2 20 CC\nrs3b X 30 GA")
    result = cli("merge.py", a, b, cwd=tmp_path)
    assert result.returncode == 0, result.stderr
    assert [line for line in result.stdout.splitlines() if not line.startswith("#")] == [
        "rs1b\t1\t10\tAA",
        "rs2b\t2\t20\tCC",
    ]
    a.write_text("# comment\nbad\n")
    result = cli("merge.py", a, cwd=tmp_path)
    assert result.returncode == 1
    assert f"{a}:2:" in result.stderr
    assert result.stdout == ""


