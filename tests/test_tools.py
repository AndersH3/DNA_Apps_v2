def cli(script, *args, cwd, optimized=False):
    command = [sys.executable] + (["-O"] if optimized else [])
    return subprocess.run(
        [*command, str(ROOT / script), *map(str, args)],
        cwd=cwd,
        text=True,
        capture_output=True,
        check=False,
    )


