def test_marker_sets_and_conflicts():
    entries = [" M1+", "M2-\n", "M1+", "M1-", "unknown", "", " \n"]
    assert process(entries) == [["M1+", "M1-", "M2-", "unknown"], ["M1+"], ["M1-", "M2-"]]
    assert entries[0] == " M1+"  # The caller's list remains untouched.
    assert conflicting_markers(*process(entries)[1:]) == ["M1"]


@given(st.lists(st.from_regex(r"M[0-9]{1,5}[+-]", fullmatch=True), max_size=50))
def test_marker_processing_is_idempotent_and_order_independent(markers):
    result = process(markers)
    assert process(result[0]) == result
    assert process(reversed(markers)) == result
    assert set(result[1]).isdisjoint(result[2])
    assert sorted(result[1] + result[2]) == result[0]


