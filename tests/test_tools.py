@pytest.mark.parametrize("left,right", list(itertools.product(CALLS, repeat=2)))
def test_complete_conflict_truth_table(left, right):
    if left == "--":
        expected = right
    elif right == "--" or left == right:
        expected = left
    else:
        expected = "XX"
    assert resolve_genotype(left, right) == expected


@given(st.lists(st.sampled_from(CALLS), min_size=1, max_size=30))
def test_merge_matches_independent_set_model(calls):
    evidence = set(calls) - {"--"}
    rows = [Row(f"rs{i}", "1", 10, call) for i, call in enumerate(calls)]
    result = merge_rows(rows)
    if len(evidence) == 1 and "XX" not in evidence:
        assert result == [Row(f"rs{len(calls) - 1}", "1", 10, next(iter(evidence)))]
    else:
        assert result == []
    # Reordering evidence must not change the selected genotype (identifier
    # precedence intentionally remains sensitive to input order).
    assert [r.genotype for r in merge_rows(reversed(rows))] == [r.genotype for r in result]


def test_genomic_sorting_and_last_identifier():
    rows = [
        parse(line)
        for line in [
            "z MT 1 A",
            "y Y 1 A",
            "x X 1 AA",
            "b 10 3 CC",
            "a 2 9 GG",
            "old 2 2 AA",
            "new 2 2 --",
            "# comment",
        ]
    ]
    assert [(r.rsid, r.chromosome, r.position) for r in merge_rows(rows)] == [
        ("new", "2", 2),
        ("a", "2", 9),
        ("b", "10", 3),
        ("x", "X", 1),
        ("y", "Y", 1),
        ("z", "MT", 1),
    ]


