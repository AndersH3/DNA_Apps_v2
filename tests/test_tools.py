def test_output_batch_refuses_overwrite(tmp_path):
    old, new = tmp_path / "old", tmp_path / "new"
    old.write_text("keep")
    with pytest.raises(FileExistsError):
        write_outputs({new: "new", old: "replace"})
    assert old.read_text() == "keep"
    assert not new.exists()


def test_output_batch_cleans_up_write_failure(tmp_path):
    first = tmp_path / "first"
    with pytest.raises(FileNotFoundError):
        write_outputs({first: "new", tmp_path / "missing" / "second": "data"})
    assert not first.exists()


